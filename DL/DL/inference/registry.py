"""Registry of the trained neural candidates that the inference interface can load.

`model_registry.json` is generated by `python -m dl.inference.build_registry` from the existing result tables
(no retraining). For each candidate configuration it records the checkpoint of the best-validation seed,
its SHA-256 (verified at load time), its role and its status.

Roles: `transformer_t_w` is the primary (default) model and `c_w_lstm` the automatic fallback used by
`dl.inference.forecast` when the primary cannot produce a valid prediction (selection evidence:
docs/model_selection.md). Every other entry is a research/comparison model, loadable only by name. EWMA is not in this
registry: it is a baseline (benchmark/reference) method, available as model="ewma" or fallback="ewma". The GNN
(GCN + LSTM) is experimental and deliberately not registered.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from cargomind_dl.config import PROJECT_ROOT  # repository root; registry paths are relative to it

REGISTRY_PATH = Path(__file__).resolve().parent / "model_registry.json"
DEFAULT_MODEL = "transformer_t_w"
FALLBACK_MODEL = "c_w_lstm"

CANDIDATES = {
    # name: (experiment, results csv relative to project root, checkpoint dir relative to project root, architecture, status)
    "transformer_t_w": ("T_w_transformer_hour_weighted", "DL/DL/artifacts/transformer/experiment_results.csv",
                        "DL/DL/artifacts/transformer/runs/T_w_transformer_hour_weighted", "transformer",
                        "primary production model (lowest validation RMSE, MAE and seed SD; within the 0.05 h tie threshold of gru and c_w_lstm)"),
    "gru": ("GRU__B_w_lstm_port_embedding_hour_weighted", "DL/DL/artifacts/experiment_results.csv",
            "DL/DL/artifacts/runs/GRU__B_w_lstm_port_embedding_hour_weighted", "gru", "research/comparison (competitive alternative; not an LSTM)"),
    "c_w_lstm": ("C_w_lstm_ewma_residual_hour_weighted", "DL/DL/artifacts/experiment_results.csv",
                 "DL/DL/artifacts/runs/C_w_lstm_ewma_residual_hour_weighted", "lstm (EWMA residual)",
                 "production fallback (best LSTM variant on validation RMSE, MAE, port-balanced RMSE and seed stability)"),
    "transformer_t": ("T_transformer", "DL/DL/artifacts/transformer/experiment_results.csv",
                      "DL/DL/artifacts/transformer/runs/T_transformer", "transformer", "research/comparison"),
    "basic_lstm": ("A_lstm", "DL/DL/artifacts/experiment_results.csv", "DL/DL/artifacts/runs/A_lstm", "lstm", "research/comparison (worse than EWMA)"),
    "lstm_b_w_original_selection": ("B_w_lstm_port_embedding_hour_weighted", "DL/DL/artifacts/experiment_results.csv",
                                    "DL/DL/artifacts/runs/B_w_lstm_port_embedding_hour_weighted", "lstm + port embedding",
                                    "research/comparison (superseded original selection; failed the independent evaluation)"),
}


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def build() -> dict:
    import pandas as pd

    entries = {}
    for name, (exp, csv, ck_dir, arch, status) in CANDIDATES.items():
        res = pd.read_csv(PROJECT_ROOT / csv)
        runs = res[res["experiment"] == exp]
        if len(runs) != 5:
            raise RuntimeError(f"{name}: expected 5 seeds of {exp} in {csv}, found {len(runs)}")
        best = runs.sort_values("val_rmse_h").iloc[0]
        ck = Path(ck_dir) / f"seed_{int(best['seed'])}.pt"
        role = "primary" if name == DEFAULT_MODEL else "fallback" if name == FALLBACK_MODEL else "research"
        entries[name] = {"experiment": exp, "architecture": arch, "role": role, "status": status, "seed": int(best["seed"]),
                         "checkpoint": str(ck), "checkpoint_sha256": sha256(PROJECT_ROOT / ck),
                         "val_rmse_h_this_seed": float(best["val_rmse_h"]),
                         "val_rmse_h_5_seed_mean": float(runs["val_rmse_h"].mean()),
                         "val_rmse_h_5_seed_sd": float(runs["val_rmse_h"].std())}
    return {"default_model": DEFAULT_MODEL, "fallback_model": FALLBACK_MODEL,
            "seed_rule": "best validation RMSE among the 5 seeds of each configuration",
            "selection_note": ("transformer_t_w is the primary model and c_w_lstm the automatic fallback (validation evidence only; "
                               "docs/model_selection.md). EWMA (alpha 0.2) is kept as a benchmark/reference and runs only when "
                               "requested. The GNN is experimental and not registered."),
            "models": entries}


def load_registry(path: Path = REGISTRY_PATH) -> dict:
    if not Path(path).exists():
        raise FileNotFoundError(f"model registry not found at {path}; run `python -m dl.inference.build_registry`")
    return json.loads(Path(path).read_text())

